import pg from 'pg';
import { Accounts } from './auth.mjs';
import { Tenants, initializeAccounts } from './tenants.mjs';
import { buildApp } from './app.mjs';
process.umask(0o077);
if(!process.env.DATABASE_URL)throw new Error('DATABASE_URL is required');
const db=new pg.Pool({connectionString:process.env.DATABASE_URL,max:8});
const lock=await db.connect();
const {rows:[leader]}=await lock.query('SELECT pg_try_advisory_lock(7301024) AS acquired');
if(!leader.acquired)throw new Error('Another worker already owns this database');
await initializeAccounts(db);
const manager=new Tenants(db),accounts=new Accounts(db);
const origins=(process.env.DASHBOARD_ORIGINS||'').split(',').map(v=>v.trim()).filter(Boolean);
if(!origins.length)throw new Error('Set DASHBOARD_ORIGINS to the application HTTPS origin');
const app=await buildApp({db,accounts,manager,origins,secureCookie:process.env.COOKIE_SECURE!=='false'});
await app.listen({port:Number(process.env.PORT)||3000,host:'0.0.0.0'});
const tick=setInterval(()=>manager.tick(),1500);
const sync=setInterval(()=>manager.sync().catch(e=>console.error(e.message)),60000);
const cleanup=setInterval(()=>db.query('DELETE FROM public.app_sessions WHERE expires_at<=now()').catch(e=>console.error(e.message)),3600000);
await manager.restore();
let stopping=false;
async function shutdown(){if(stopping)return;stopping=true;clearInterval(tick);clearInterval(sync);clearInterval(cleanup);await app.close();await manager.close();await lock.query('SELECT pg_advisory_unlock(7301024)');lock.release();await db.end();process.exit(0);}
process.on('SIGTERM',shutdown);process.on('SIGINT',shutdown);
